#!/usr/bin/env node

import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, "..", "..", "..");
const corePackagePath = join(repoRoot, "core", "frontend", "package.json");
const installedRoot = join(
  repoRoot,
  "core",
  "frontend",
  "node_modules",
  "@shipctl",
  "cordis-source",
);
const cordisPackagePath = join(installedRoot, "packages", "core", "package.json");
const entryPoint = join(installedRoot, "packages", "core", "src", "index.ts");
const outputPath = join(
  repoRoot,
  "core",
  "frontend",
  "runtime",
  "cordis",
  "vendor",
  "cordis.js",
);

const corePackage = JSON.parse(await readFile(corePackagePath, "utf8"));
const cordisPackage = JSON.parse(await readFile(cordisPackagePath, "utf8"));
const sourceSpecifier = corePackage.dependencies?.["@shipctl/cordis-source"];
assert.equal(typeof sourceSpecifier, "string", "Cordis source dependency is missing");
const revision = sourceSpecifier.match(/#([0-9a-f]{40})$/)?.[1];
assert.ok(revision, `Cordis source must use an exact Git revision: ${sourceSpecifier}`);

const banner = [
  "/*!",
  ` * Cordis ${cordisPackage.version}, source revision ${revision}`,
  " * https://github.com/cordiverse/cordis",
  " * Copyright (c) 2021-present Shigma; MIT License",
  " * Generated by ops/architecture/bin/build-cordis-runtime.mjs; do not edit.",
  " */",
].join("\n");

const result = await build({
  absWorkingDir: repoRoot,
  banner: { js: banner },
  bundle: true,
  entryPoints: [entryPoint],
  format: "esm",
  legalComments: "eof",
  logLevel: "warning",
  nodePaths: [join(repoRoot, "core", "frontend", "node_modules")],
  platform: "browser",
  target: "es2021",
  write: false,
});
const generated = result.outputFiles?.[0]?.text;
assert.ok(generated, "Cordis runtime bundle was not generated");

const mode = process.argv[2] ?? "--check";
if (mode === "--write") {
  await writeFile(outputPath, generated);
  console.log(`wrote ${relative(repoRoot, outputPath)} from Cordis ${revision}`);
} else if (mode === "--check") {
  const committed = await readFile(outputPath, "utf8");
  assert.equal(
    committed,
    generated,
    `Cordis runtime bundle is stale; run node ${relative(repoRoot, fileURLToPath(import.meta.url))} --write`,
  );
  console.log(`verified ${relative(repoRoot, outputPath)} from Cordis ${revision}`);
} else {
  throw new Error(`Unknown mode: ${mode}. Use --check or --write.`);
}
