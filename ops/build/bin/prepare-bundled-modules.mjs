#!/usr/bin/env node

import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

import { buildPluginArtifactStaging } from "../../architecture/lib/plugin-artifact-build.mjs";

const exec = promisify(execFile);
const repositoryRoot = path.resolve(fileURLToPath(new URL("../../../", import.meta.url)));
const generatedRoot = path.join(repositoryRoot, "src-tauri/generated");
const archiveRoot = path.join(generatedRoot, "modules");
const rustIndex = path.join(generatedRoot, "bundled_modules.rs");

async function manifest(relativePath) {
  const { stdout } = await exec("yq", ["-o=json", ".", relativePath], {
    cwd: repositoryRoot,
  });
  return JSON.parse(stdout);
}

async function packageArtifact({ sourceDirectory, outputPath, shipctlPath }) {
  const temporaryRoot = await mkdtemp(path.join(os.tmpdir(), "shipctl-plugin-artifact-"));
  try {
    const stagingDirectory = path.join(temporaryRoot, "staging");
    await buildPluginArtifactStaging({ sourceDirectory, stagingDirectory });
    const packaged = await exec(shipctlPath, [
      "modules",
      "pack",
      stagingDirectory,
      "--to",
      outputPath,
      "--output",
      "json",
    ], { cwd: repositoryRoot });
    assert.equal(packaged.stderr, "", "Artifact pack diagnostics must use structured stdout");
    const packageReport = JSON.parse(packaged.stdout);
    assert.equal(packageReport.status, "success");
    assert.equal(packageReport.code, "module.artifact.packed");
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true });
  }
}

const moduleNames = (await readdir(path.join(repositoryRoot, "modules"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name);
const runtimeModules = [];
for (const moduleName of moduleNames.sort()) {
  const manifestPath = path.join("modules", moduleName, "module.yaml");
  try {
    const declaration = await manifest(manifestPath);
    if (declaration.frontend?.delivery === "runtime-artifact") {
      runtimeModules.push({ declaration, manifestPath });
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
}

await exec("cargo", ["build", "-p", "shipctl-cli"], { cwd: repositoryRoot });
await rm(generatedRoot, { recursive: true, force: true });
await mkdir(archiveRoot, { recursive: true });

const rows = [];
for (const { declaration, manifestPath } of runtimeModules) {
  const artifactSource = declaration.frontend.artifact;
  assert.equal(typeof artifactSource, "string", `${manifestPath} requires frontend.artifact`);
  const template = JSON.parse(await readFile(
    path.join(repositoryRoot, artifactSource, "module.template.json"),
    "utf8",
  ));
  const archiveName = `${template.id}.shipctl-module`;
  await packageArtifact({
    sourceDirectory: path.join(repositoryRoot, artifactSource),
    outputPath: path.join(archiveRoot, archiveName),
    shipctlPath: path.join(repositoryRoot, "target/debug/shipctl"),
  });
  rows.push({ id: template.id, archiveName });
}

const generated = [
  "// Generated by ops/build/bin/prepare-bundled-modules.mjs.",
  "// Do not edit.",
  "pub(super) const BUNDLED_ARTIFACTS: &[BundledArtifact] = &[",
  ...rows.map(({ id, archiveName }) => [
    "    BundledArtifact {",
    `        module_id: ${JSON.stringify(id)},`,
    `        archive: include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/generated/modules/${archiveName}\")),`,
    "    },",
  ].join("\n")),
  "];",
  "",
].join("\n");
await writeFile(rustIndex, generated);

process.stdout.write(`${JSON.stringify({
  schemaVersion: 1,
  operation: "build.prepare-bundled-modules",
  status: "success",
  modules: rows.map(({ id }) => id),
})}\n`);
